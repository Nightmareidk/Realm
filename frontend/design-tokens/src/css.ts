import { type Oklch, toCss } from "./color";
import { type EditionTokens, editions, motion, type RegionName, radius } from "./tokens";

const kebab = (s: string) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);

function editionVars(e: EditionTokens): string[] {
  const lines: string[] = [];
  for (const [key, value] of Object.entries(e)) {
    if (key === "regions") continue;
    lines.push(`--r-${kebab(key)}: ${toCss(value as Oklch)};`);
  }
  for (const [name, inks] of Object.entries(e.regions) as [
    RegionName,
    EditionTokens["regions"][RegionName],
  ][]) {
    for (const [role, value] of Object.entries(inks)) {
      lines.push(`--r-${name}-${role}: ${toCss(value)};`);
    }
  }
  return lines;
}

const indent = (lines: string[], n: number) => lines.map((l) => `${" ".repeat(n)}${l}`).join("\n");

/**
 * Dark first: the night edition is everyone's default. The day edition applies only when
 * a person chooses it (`data-theme="day"` on <html>, set from their Appearance setting).
 */
export function buildCss(): string {
  const day = editionVars(editions.day);
  const night = editionVars(editions.night);
  const shared = [
    ...Object.entries(motion).map(([k, v]) =>
      k.startsWith("ease") ? `--r-${kebab(k)}: ${v};` : `--r-dur-${kebab(k)}: ${v};`,
    ),
    ...Object.entries(radius).map(([k, v]) => `--r-radius-${k}: ${v};`),
  ];

  return `/* Generated by @realm/design-tokens (pnpm --filter @realm/design-tokens build). Do not edit. */

:root {
${indent(shared, 2)}
}

:root,
:root[data-theme="night"] {
  color-scheme: dark;
${indent(night, 2)}
}

:root[data-theme="day"] {
  color-scheme: light;
${indent(day, 2)}
}
`;
}

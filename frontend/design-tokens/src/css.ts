import { motion, radius, roles, THEME_ORDER, type ThemeTokens, themes } from "./tokens";

const kebab = (s: string) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);
const indent = (lines: string[], n: number) => lines.map((l) => `${" ".repeat(n)}${l}`).join("\n");

/** A theme's roles: the action colour and what derives from it, and the three lights. */
function themeVars(t: ThemeTokens): string[] {
  return [
    `--r-accent: ${t.accent};`,
    `--r-on-accent: ${t.onAccent};`,
    `--r-light-1: ${t.lights[0]};`,
    `--r-light-2: ${t.lights[1]};`,
    `--r-light-3: ${t.lights[2]};`,
    `--r-glow: ${t.glow};`,
  ];
}

/**
 * The roles every component reads. Neutral roles live on :root; the person's theme sets the
 * accent and the lights (`data-accent` on <html>, from their Appearance setting; Mint when unset).
 * Derived roles (focus, your chat bubbles, mentions, selection) follow the accent through
 * `var()`, so a theme only writes its own six values.
 */
export function buildCss(): string {
  const shared = [
    ...Object.entries(roles).map(([k, v]) => `--r-${kebab(k)}: ${v};`),
    ...themeVars(themes.mint),
    "--r-focus: var(--r-accent);",
    "--r-mention: var(--r-accent);",
    "--r-link: var(--r-text);",
    "--r-bubble-mine: var(--r-accent);",
    "--r-on-bubble-mine: var(--r-on-accent);",
    "--r-bubble-theirs: var(--r-surface-sunken);",
    "--r-selection: color-mix(in srgb, var(--r-accent) 34%, transparent);",
    ...Object.entries(motion).map(([k, v]) =>
      k.startsWith("ease") ? `--r-${kebab(k)}: ${v};` : `--r-dur-${kebab(k)}: ${v};`,
    ),
    ...Object.entries(radius).map(([k, v]) => `--r-radius-${k}: ${v};`),
  ];
  const variants = THEME_ORDER.filter((id) => id !== "mint")
    .map((id) => `:root[data-accent="${id}"] {\n${indent(themeVars(themes[id]), 2)}\n}`)
    .join("\n\n");

  return `/* Generated by @realm/design-tokens (pnpm --filter @realm/design-tokens build). Do not edit. */

:root {
  color-scheme: dark;
${indent(shared, 2)}
}

${variants}
`;
}
